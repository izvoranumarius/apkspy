"""Regenerates tests/emu_fixture.inc from EmuFix.java and UiFix.java.

Needs a JDK (javac and java on PATH, from the same JDK) and the Android SDK (platforms/android-34 and
build-tools/34.0.0, found through ANDROID_HOME or the default Windows location). A fresh RSA key pair is made for each
run and substituted for the @...@ placeholders, so no key is kept in the sources; the compiled bytes in the .inc hold
that run's throwaway test key.

    python tests/emu_fixture/make.py
"""
import glob
import os
import subprocess
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
sdk = os.environ.get("ANDROID_HOME") or os.path.expandvars(r"%LOCALAPPDATA%\Android\Sdk")
jar = os.path.join(sdk, "platforms", "android-34", "android.jar")
d8 = os.path.join(sdk, "build-tools", "34.0.0", "d8.bat" if os.name == "nt" else "d8")

GEN = """
import java.security.*; import javax.crypto.Cipher; import java.util.Base64;
public class Gen { public static void main(String[] a) throws Exception {
  KeyPairGenerator g = KeyPairGenerator.getInstance("RSA"); g.initialize(1024); KeyPair k = g.generateKeyPair();
  Cipher c = Cipher.getInstance("RSA/ECB/PKCS1Padding"); c.init(Cipher.ENCRYPT_MODE, k.getPublic());
  System.out.println(Base64.getEncoder().encodeToString(k.getPublic().getEncoded()));
  System.out.println(Base64.getEncoder().encodeToString(k.getPrivate().getEncoded()));
  System.out.println(Base64.getEncoder().encodeToString(c.doFinal("only the private key".getBytes("UTF-8"))));
  Cipher o = Cipher.getInstance("RSA/ECB/OAEPWithSHA-256AndMGF1Padding"); o.init(Cipher.ENCRYPT_MODE, k.getPublic());
  System.out.println(Base64.getEncoder().encodeToString(o.doFinal("sealed by the JDK".getBytes("UTF-8"))));
}}
"""

EXPECT = """
public class Expect { public static void main(String[] a) throws Exception {
  String[][] calls = {{"exceptions","12"},{"exceptions","x"},{"reflect","abc"},{"gcm","attack at dawn"},{"rsa","hello rsa"},{"objects","hello"},{"oaep","padded"},{"numbers","abcdef"},{"collections","b,a,c,a,b,d,a"}};
  for (String[] c : calls) System.out.println(c[0] + "\\t" + c[1] + "\\t" + EmuFix.class.getMethod(c[0], String.class).invoke(null, c[1]));
}}
"""


def run(*command, **options):
    return subprocess.run(list(command), check=True, **options)


def write(path, text, newline="\n"):
    with open(path, "w", encoding="utf-8", newline=newline) as f:
        f.write(text)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as work:
    os.chdir(work)
    write("Gen.java", GEN)
    run("javac", "-d", "gen", "Gen.java")
    public, private, sealed, oaep = run("java", "-cp", "gen", "Gen", capture_output=True, text=True).stdout.split()

    source = read(os.path.join(here, "EmuFix.java"))
    for placeholder, value in (("@PUBLIC@", public), ("@PRIVATE@", private), ("@FOR_PRIVATE@", sealed), ("@FOR_OAEP@", oaep)):
        source = source.replace(placeholder, value)
    write("EmuFix.java", source)
    write("UiFix.java", read(os.path.join(here, "UiFix.java")))
    run("javac", "--release", "8", "-g:none", "-cp", jar, "-d", "classes", "EmuFix.java", "UiFix.java")
    os.makedirs("dex")
    run(d8, "--min-api", "26", "--lib", jar, "--output", "dex", *glob.glob("classes/*.class"))

    write("Expect.java", EXPECT)
    run("javac", "--release", "8", "-cp", "classes", "-d", "host", "Expect.java")
    results = run("java", "-cp", "host" + os.pathsep + "classes", "Expect", capture_output=True, text=True).stdout
    with open("dex/classes.dex", "rb") as f:
        dex = f.read()
    os.chdir(here)

lines = ["// Generated by tests/emu_fixture/make.py: the DEX of tests/emu_fixture/*.java (javac --release 8 -g:none, then d8)",
         "// and what the host JVM returns for the calls the test makes. The RSA key inside is a throwaway test key.",
         "static const unsigned char kEmuFixtureDex[] = {"]
lines += ["    " + ",".join(str(b) for b in dex[i:i + 20]) + "," for i in range(0, len(dex), 20)]
lines += ["};", "static const char* const kEmuExpected[][3] = {"]
for row in results.strip().splitlines():
    name, argument, result = row.split("\t")
    result = result.replace("\\", "\\\\").replace('"', '\\"')
    lines.append('    {"%s", "%s", "%s"},' % (name, argument, result))
lines.append("};")
write(os.path.join(here, "..", "emu_fixture.inc"), "\n".join(lines) + "\n", newline="\r\n")
print("emu_fixture.inc written: %d bytes of DEX" % len(dex))
